import { chromium } from 'playwright';
import { createServer } from '../server.mjs';
import { once } from 'node:events';
import { mkdir } from 'node:fs/promises';
import assert from 'node:assert/strict';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const artifactPath=fileURLToPath(new URL('../../.site-artifacts/',import.meta.url));
await mkdir(artifactPath,{recursive:true});
const server=createServer();server.listen(0,'127.0.0.1');await once(server,'listening');
const base=`http://127.0.0.1:${server.address().port}`;
let browser;
try{
  browser=await chromium.launch({channel:process.env.BROWSER_CHANNEL||'msedge',headless:true});
  const page=await browser.newPage({viewport:{width:1440,height:1120},deviceScaleFactor:1});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto(base);await page.waitForFunction(()=>document.querySelector('#eventCount').textContent.replace(/\D/g,'')==='2000');
  await page.screenshot({path:path.join(artifactPath,'dashboard-desktop.png'),fullPage:true});
  assert.equal(await page.locator('#gaugeNumber').textContent(),'7');
  await page.locator('#advancedOptions').click();
  await page.locator('#fromDate').fill('2026-10-01');await page.locator('#toDate').fill('2026-10-01');await page.locator('#toDate').dispatchEvent('change');
  assert.equal(await page.locator('#entriesMetric').textContent(),'48');assert.equal(await page.locator('#exitsMetric').textContent(),'40');
  await page.locator('[data-page="events"]').click();await page.locator('#directionFilter').selectOption('entrada');await page.locator('#validationFilter').selectOption('ACEPTADO');
  assert.match(await page.locator('#tableCount').textContent(),/48 eventos/);
  await page.locator('#nextPage').click();assert.equal(await page.locator('#pageCount').textContent(),'2 / 3');
  const [csvDownload]=await Promise.all([page.waitForEvent('download'),page.locator('#exportButton').click()]);await csvDownload.saveAs(path.join(artifactPath,'export.csv'));
  await page.locator('#importFile').setInputFiles(path.join(artifactPath,'export.csv'));await page.waitForFunction(()=>document.querySelector('#eventCount').textContent==='48');
  await page.locator('[data-mode="demo"]').click();
  assert.equal(await page.locator('#activeAlert').isHidden(),true);
  await page.locator('#audioToggle').click();assert.equal(await page.locator('#audioToggle').getAttribute('aria-pressed'),'true');
  await page.locator('#demoExit').click();assert.equal(await page.locator('#gaugeNumber').textContent(),'0');
  for(let i=0;i<8;i++)await page.locator('#demoEntry').click();assert.equal(await page.locator('#activeAlertTitle').textContent(),'Aforo alto');assert.equal(await page.locator('#activeAlert').isVisible(),true);
  for(let i=0;i<2;i++)await page.locator('#demoEntry').click();assert.equal(await page.locator('#gaugeNumber').textContent(),'10');assert.equal(await page.locator('#occupancyStatus').textContent(),'Completo');assert.equal(await page.locator('#activeAlertTitle').textContent(),'Capacidad máxima');
  await page.screenshot({path:path.join(artifactPath,'alert-capacity-desktop.png'),fullPage:true});
  await page.locator('#demoEntry').click();assert.equal(await page.locator('#activeAlertTitle').textContent(),'Acceso rechazado');
  await page.locator('#demoExit').click();assert.equal(await page.locator('#gaugeNumber').textContent(),'9');
  await page.locator('#demoIncomplete').click();assert.match(await page.locator('#eventsBody').textContent(),/Paso incompleto/);assert.equal(await page.locator('#activeAlertTitle').textContent(),'Movimiento para revisar');
  await page.locator('[data-page="alerts"]').click();assert.match(await page.locator('#eventsBody').textContent(),/Revisar datos/);
  await page.locator('[data-page="connection"]').click();
  const [configDownload]=await Promise.all([page.waitForEvent('download'),page.locator('#downloadConfig').click()]);assert.equal(configDownload.suggestedFilename(),'config.h');
  await page.locator('[data-page="overview"]').click();await page.locator('[data-mode="live"]').click();assert.equal(await page.locator('#gaugeNumber').textContent(),'—');
  await page.reload();await page.waitForFunction(()=>document.querySelector('#eventCount').textContent.replace(/\D/g,'')==='2000');
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true,'Sin desbordamiento horizontal en móvil');
  await page.screenshot({path:path.join(artifactPath,'dashboard-mobile.png'),fullPage:true});
  await page.locator('[data-page="connection"]').click();assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true,'Conexión adaptable a móvil');
  await page.screenshot({path:path.join(artifactPath,'connection-mobile.png'),fullPage:true});
  assert.deepEqual(errors,[],'Sin errores de JavaScript');
  console.log('OK: histórico, fechas, filtros, paginación, exportación/importación, demo, límites de aforo, descargas y diseño móvil.');
}finally{await browser?.close();server.close();}
